create table if not exists public.nexus_messages (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    role text not null check (role in ('user', 'assistant')),
    content text not null,
    created_at timestamptz not null default now()
);

do $$
begin
    if exists (
        select 1 from information_schema.columns
        where table_schema = 'public' and table_name = 'nexus_messages'
          and column_name = 'user_id' and data_type <> 'uuid'
    ) then
        alter table public.nexus_messages drop constraint if exists nexus_messages_user_id_fkey;
        alter table public.nexus_messages alter column user_id type uuid using null::uuid;
    end if;
end $$;

alter table public.nexus_messages alter column user_id set not null;
alter table public.nexus_messages drop constraint if exists nexus_messages_user_id_fkey;
alter table public.nexus_messages add constraint nexus_messages_user_id_fkey
    foreign key (user_id) references auth.users(id) on delete cascade;

create index if not exists nexus_messages_user_created_idx
    on public.nexus_messages (user_id, created_at);

create table if not exists public.nexus_profiles (
    user_id uuid primary key references auth.users(id) on delete cascade,
    email text not null,
    updated_at timestamptz not null default now()
);

alter table public.nexus_messages enable row level security;

drop policy if exists "NEXUS users can read messages" on public.nexus_messages;
create policy "NEXUS users can read messages"
    on public.nexus_messages for select to authenticated
    using (auth.uid() = user_id);

drop policy if exists "NEXUS users can add messages" on public.nexus_messages;
create policy "NEXUS users can add messages"
    on public.nexus_messages for insert to authenticated
    with check (auth.uid() = user_id);

drop policy if exists "NEXUS users can delete messages" on public.nexus_messages;
create policy "NEXUS users can delete messages"
    on public.nexus_messages for delete to authenticated
    using (auth.uid() = user_id);

alter table public.nexus_profiles enable row level security;

drop policy if exists "NEXUS users can read own profile" on public.nexus_profiles;
create policy "NEXUS users can read own profile"
    on public.nexus_profiles for select to authenticated
    using (auth.uid() = user_id);

drop policy if exists "NEXUS users can create own profile" on public.nexus_profiles;
create policy "NEXUS users can create own profile"
    on public.nexus_profiles for insert to authenticated
    with check (auth.uid() = user_id);

drop policy if exists "NEXUS users can update own profile" on public.nexus_profiles;
create policy "NEXUS users can update own profile"
    on public.nexus_profiles for update to authenticated
    using (auth.uid() = user_id)
    with check (auth.uid() = user_id);
